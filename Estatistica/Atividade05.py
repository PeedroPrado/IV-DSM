def tabela_frequencias(lista, titulo=""):
    freq = {}
    for valor in lista:
        if valor in freq:
            freq[valor] += 1
        else:
            freq[valor] = 1

    N = len(lista)

    if titulo:
        print(f"\n{'='*40}")
        print(f"  {titulo}")
        print(f"{'='*40}")

    print(f"{'Valor':>6} | {'FA':>4} | {'FR':>7} | {'FP':>8}")
    print("-" * 35)

    for valor in sorted(freq):
        fa = freq[valor]
        fr = fa / N
        fp = fr * 100
        print(f"{valor:>6} | {fa:>4} | {fr:>7.4f} | {fp:>7.2f}%")

    print("-" * 35)
    print(f"{'Total':>6} | {N:>4} | {'1.0000':>7} | {'100.00%':>8}")


